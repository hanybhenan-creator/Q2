CLEAN = ["GTWL", "TMGH", "GRCA", "IDRE", "ISMA", "CCAP", "EMFD", "CLHO"]
RATIO = 365.2422 / 360.0          # تصحيح الانزياح: النبوى ← الشمسى
BIBLICAL = [2520, 1260, 1290, 1335, 2300, 5040, 7200]
PERIODS = sorted({p for b in BIBLICAL for p in (b, round(b * RATIO))})


def load_series(path, ticker):
    rows = []
    with open(path, newline="", encoding="utf-8", errors="ignore") as f:
        r = csv.DictReader(f)
        for x in r:
            if x["ticker"] != ticker:
                continue
            try:
                d = dt.datetime.strptime(x["date"][:10], "%Y-%m-%d").date()
                c = float(x["close"])
            except (ValueError, KeyError):
                continue
            if c > 0:
                rows.append((d, c))
    rows.sort()
    return rows


def pivots(rows, w=20):
    """قمم/قيعان رئيسية: أعلى/أدنى إغلاق فى ±w جلسة. مُعلَن سلفًا، لا اختيار."""
    out = []
    for i in range(w, len(rows) - w):
        seg = rows[i - w:i + w + 1]
        c = rows[i][1]
        if c == max(s[1] for s in seg):
            out.append((rows[i][0], c, "قمة"))
        elif c == min(s[1] for s in seg):
            out.append((rows[i][0], c, "قاع"))
    return out


def test_cycles(csv_path, anchor_shift=37, tol=5):
    hdr("٥. اختبار مُعلَن سلفًا — مضاعفات دورات دانيال على قمم السوق")
    print("  **التصريح قبل النظر:**")
    print("   • الدورات (من دانيال) بصيغتين: كما هى، وبعد تصحيح ٣٦٠→٣٦٥.٢٤٢٢")
    print(f"     (معامل {RATIO:.5f}). فالدورة النبوية ٢٥٢٠ يومًا = {round(2520*RATIO)} يومًا شمسيًّا.")
    print("   • القمة/القاع: إغلاقٌ هو الأقصى/الأدنى فى ±٢٠ جلسة.")
    print("   • المرساة: **أوّل** قمة/قاع فى السلسلة — لا اختيار.")
    print("   • كل القمم والقيعان التالية تُقاس، بلا استثناء.")
    print("   • «إصابة» = المسافة إلى أقرب مضاعف ≤ ٥ أيام تقويمية.")
    print(f"   • الضابط: نفس البروتوكول بمرساةٍ مُزاحة +{anchor_shift} يومًا.")
    print()
    files = [t for t in CLEAN]
    total = defaultdict(lambda: [0, 0])
    ctrl = defaultdict(lambda: [0, 0])
    detail = []

    for t in files:
        rows = load_series(csv_path, t)
        if len(rows) < 400:
            continue
        pv = pivots(rows)
        if len(pv) < 6:
            continue
        anchor = pv[0][0]
        hits = defaultdict(int)
        n = 0
        for d, c, kind in pv[1:]:
            n += 1
            dd = (d - anchor).days
            for p in PERIODS:
                r = dd % p
                if min(r, p - r) <= tol:
                    hits[p] += 1
                    total[p][0] += 1
                total[p][1] += 1
        detail.append((t, len(rows), n, hits))

        # الضابط
        anch2 = anchor + dt.timedelta(days=anchor_shift)
        for d, c, kind in pv[1:]:
            dd = (d - anch2).days
            for p in PERIODS:
                r = dd % p
                if min(r, p - r) <= tol:
                    ctrl[p][0] += 1
                ctrl[p][1] += 1

    print(f"  {'السهم':>6} {'صفوف':>7} {'قمم/قيعان':>10}  " +
          "  ".join(f"{p:>5}" for p in PERIODS))
    for t, nrows, n, hits in detail:
        print(f"  {t:>6} {nrows:>7} {n:>10}  " +
              "  ".join(f"{hits[p]:>5}" for p in PERIODS))

    print(f"\n  {'الدورة':>7} {'المُشاهَد':>9} {'من':>6} {'النسبة':>7} "
          f"{'الضابط':>8} {'نسبة الضابط':>11}")
    for p in PERIODS:
        h, n = total[p]
        ch, cn = ctrl[p]
        print(f"  {p:>7} {h:>9} {n:>6} {100*h/max(n,1):>6.1f}% "
              f"{ch:>8} {100*ch/max(cn,1):>10.1f}%")

    print("\n  ⇒ كيف يُقرأ هذا بلا إحصاء:")
    print("     إن تساوى «المُشاهَد» و«الضابط» فالدورة **لا تُضيف شيئًا** على مرساةٍ")
    print("     عشوائية — لأن التوليد نفسه (٥ أيام تسامح ÷ دورة طويلة) يُنتج إصابات.")
    print("     وإن زاد المُشاهَد وحده، فذاك أثرٌ يستحق أن يُعلَن ويُعاد على أداةٍ أخرى.")


def test_seasons(csv_path):
    hdr("٦. «لمواسم» (moed) — هل تتجمّع الانعطافات فى برجٍ أو موسم؟")
    print("  هذه هى الوظيفة الثانية فى تك ١:١٤ («أوقات/مواسم»)، وهى تُختبر على")
    print("  **الموضع الشمسى** لا على التاريخ: كل انعطاف ← برجُ الشمس فيه.")
    print("  والتوزيع المتساوى هو الفرض الصفرى؛ والضابط = نفس الانعطافات مُزاحة ٣٧ يومًا.")
    try:
        import swisseph as swe
    except ImportError:
        print("  (swisseph غير مثبّت ⇒ تخطَّ)")
        return
    F = swe.FLG_MOSEPH
    signs = ("الحمل", "الثور", "الجوزاء", "السرطان", "الأسد", "العذراء",
             "الميزان", "العقرب", "القوس", "الجدى", "الدلو", "الحوت")

    def sector(d):
        jd = swe.julday(d.year, d.month, d.day, 12.0)
        lon = swe.calc_ut(jd, swe.SUN, F)[0][0]
        return int(lon // 30)

    real, ctrl = [0] * 12, [0] * 12
    n = 0
    for t in CLEAN:
        rows = load_series(csv_path, t)
        if len(rows) < 400:
            continue
        for d, c, kind in pivots(rows):
            real[sector(d)] += 1
            ctrl[sector(d + dt.timedelta(days=37))] += 1
            n += 1
    exp = n / 12
    print(f"\n  الانعطافات: {n} · المتوقَّع لكل برج إن لا تفضيل: {exp:.1f}\n")
    print(f"  {'البرج':>8} {'المُشاهَد':>9} {'الضابط':>8} {'الفرق عن المتوقَّع':>18}")
    for i, sname in enumerate(signs):
        print(f"  {sname:>8} {real[i]:>9} {ctrl[i]:>8} {real[i]-exp:>+18.1f}")
    print(f"\n  المدى: أدنى {min(real)} · أعلى {max(real)}  (= {min(real)/exp*100:.0f}%–{max(real)/exp*100:.0f}% من المتوقَّع)")
    print(f"  والضابط: أدنى {min(ctrl)} · أعلى {max(ctrl)}")
    print("  ⇒ الحكم: يُقرأ بالمدى لا بالرقم الواحد. فإذا كان التشتيّت فى الضابط مثله")
    print("     فى الحقيقى، فالتجمّع موسمىُّ الظاهرِ لا موسمىُّ السبب. (والأرقام أعلاه تحكم.)")


