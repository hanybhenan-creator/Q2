def audit_hexagon():
    hdr("٤. المسدّس — أعداده وحلقتُه")
    print("   H(n) = 3n(n−1) + 1  (ن = 1 عند المركز)")
    prev = 1
    for n in range(1, 8):
        h = 3 * n * (n - 1) + 1
        diff = h - prev
        print(f"   الحلقة {n}: {h:>4}   (فرق {diff:>4} = 6×{n-1})   "
              f"٣٦٠° ÷ {n if n>1 else 1} = {360/n:6.1f}")
        prev = h
    print("   ⇒ فرق الحلقة 6n، وفيه 6 أضلاع؛ فكل ضلع n رقمًا. ولهذا سُمّى «المسدّس».")
    print("     والزاوية 360/6 = 60° للضلع، و30° لنصفه — وهى أرقام خطاب الصويا.")


