def audit_digital_root():
    hdr("٥. الجذر الرقمى — علاقته بمواضع المربع")
    print("   الدرجة المختزلة (0–9) لكل رقم على محور الصفر (المربعات الفردية):")
    for n in (1, 9, 25, 49, 81, 121, 169, 225, 289, 361):
        print(f"   {n:>4}  جذره الفلكى {math.sqrt(n):>5.1f}  "
              f"الجذر الرقمى {root_digit(n)}   الدرجة {sq9_degree(n):6.2f}°")
    print("   ⇒ لاحظ: محور الصفر يجمع 1·9·25·49·81 — وجذورها الرقمية 1·9·7·4·9،")
    print("     أى **ليست** واحدة. فالقول الشائع «أرقام المحور تُختزل إلى رقم واحد» خطأ.")
    residues = {}
    for k in range(1, 200):
        n = (2 * k + 1) ** 2
        residues.setdefault(root_digit(n), []).append(n)
    print("\n   والأصدق: الأرقام على محور الصفر ليست متساوية الجذر الرقمى —")
    print("   بل لا تخرج عن **البواقى التربيعية** mod 9:")
    for r in sorted(residues):
        print(f"     الباقى {r}:  {', '.join(str(x) for x in residues[r][:5])} …")
    print("   ⇒ فالذى يبقى صحيحًا هو: (أ) الأعداد على محور واحد لا تأخذ إلا بواقى")
    print("     بعينها mod 9 — وهذا حقيقى؛ (ب) الجذور الرقمية تتوزّع بالتساوى على")
    print("     الأعداد الطبيعية كلها — وهذا يهدم أى «طاقة» خاصةٍ لرقمٍ بذاته.")


