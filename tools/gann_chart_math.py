"""
هندسة جان الرقمية — تحقّقٌ حسابى لا تفسير.

كل ما يُسمّى «هندسة مقدسة» أو «طاقة الرقم» عند جان يقوم فى أصله على
**متطابقاتٍ عددية** يمكن إثباتها أو إسقاطها بالحساب، ويعلوها **معانٍ** لا
يمكن إثباتها بالحساب. هذا الملف يفصل الأول عن الثانى:

  ١. مربع التسعة: دوران ٣٦٠° = إضافة ٢ إلى الجذر ثم التربيع.
  ٢. الأمثلة: المربعات الفردية على محور الصفر، والزوجية على المحور المقابل.
  ٣. النقاط الربعية والنصفية (٤٥° و٩٠°).
  ٤. المسدّس: أعداده وحلقة ٣٦٠°.
  ٥. أرقام «الجذر الرقمى» (digital root) وعلاقتها بمواضع المربع.
  ٦. أضلاع الدائرة التى تُعطى درجاتٍ صحيحة (الكسور المгармونية).
  ٧. تربيع السعر بالزمن: أين يلتقى الإحداثيان فعلًا.
  ٨. زمن الكوكب: الشمس ١° فى اليوم تقريبًا — ومنها «نقطة = يوم».

التشغيل:
    python3 tools/gann_chart_math.py
"""

import math

LINE = "=" * 78


def hdr(t):
    print("\n" + LINE + "\n " + t + "\n" + LINE)


def root_digit(n):
    n = abs(int(n))
    return 0 if n == 0 else 1 + (n - 1) % 9


# ─────────────────────────────────────────────────────────────────────
# ١ + ٢ + ٣ — مربع التسعة
# ─────────────────────────────────────────────────────────────────────

def sq9_degree(n):
    """درجة الرقم على مربع التسعة: (√n − 1) × 180 (المركز = 1)."""
    return ((math.sqrt(n) - 1.0) * 180.0) % 360.0


def sq9_number(deg):
    """الرقم الواقع على درجة معيّنة (أقرب عدد صحيح)."""
    return (1.0 + deg / 180.0) ** 2


def audit_sq9():
    hdr("١–٣. مربع التسعة — المتطابقات")

    print("أ) دوران ٣٦٠° = إضافة ٢ إلى الجذر ثم التربيع (بلا تقريب):")
    ok = True
    for n in (16, 25, 40, 100, 435, 8729):
        a = (math.sqrt(n) + 2) ** 2
        d0, d1 = sq9_degree(n), sq9_degree(a)
        same = abs((d1 - d0) % 360.0) < 1e-9
        ok &= same
        print(f"   {n:>6}:  الدرجة {d0:7.3f}°  →  (√n+2)² = {a:10.3f}  درجته {d1:7.3f}°  "
              f"{'✔ +360°' if same else '✘'}")
    print(f"   ⇒ {'المتطابقة صحيحة بالضبط لكل الأرقام' if ok else 'لا تصحّ'}")
    print("     وهى متطابقةٌ جبرية: ((√n+2)−1)×180 = (√n−1)×180 + 360. لا عيب فيها.")

    print("\nب) ٤٥° = إضافة ٠.٢٥ إلى الجذر  ·  ٩٠° = ٠.٥  ·  ٣٦٠° = ٢:")
    for n in (16, 20, 435):
        for step, label in ((0.25, "٤٥°"), (0.5, "٩٠°"), (2.0, "٣٦٠°")):
            a = (math.sqrt(n) + step) ** 2
            d = (sq9_degree(a) - sq9_degree(n)) % 360
            print(f"   من {n:>5} + {step:>4} (√) = {a:9.3f}   ⇒  +{d:6.2f}°  ({label})")
        print()
    print("   ⇒ القاعدة: كل ٠.٢٥ فى الجذر = ٤٥°، وكل ٢ = دورة كاملة.")
    print("     وهى متطابقةٌ بالتعريف، لا قاعدةَ سوق.")

    print("\nج) المربعات الكاملة — أين تقع؟")
    print(f"   {'الرقم':>8} {'جذره':>7} {'الدرجة':>9}  المحور")
    for n in (1, 4, 9, 16, 25, 36, 49, 64, 81, 100):
        d = sq9_degree(n)
        axis = ("الصفر/٣٦٠ (شرق)" if abs(d) < 1e-9 or abs(d - 360) < 1e-9
                else "١٨٠ (غرب)" if abs(d - 180) < 1e-6 else "—")
        print(f"   {n:>8} {math.sqrt(n):>7.1f} {d%360:>9.2f}  {axis}")
    print("   ⇒ المربعات الفردية (1·9·25·49·81) على ٠°/٣٦٠°، والزوجية على ١٨٠°.")
    print("     وهو ما يسمّيه جان «محور الصفر» و«الخط الشمالى-الجنوبى».")

    print("\nد) النقاط الربعية والنصفية تخرج أعدادًا صحيحة:")
    for deg in (45, 90, 135, 180, 225, 270, 315, 360):
        v = sq9_number(deg)
        print(f"   {deg:>3}° ← √n = 1 + {deg/180:.2f} = {1+deg/180:.2f} → n = {v:9.3f}")


