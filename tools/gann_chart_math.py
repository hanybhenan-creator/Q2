def audit_circle():
    hdr("٦. تقسيمات ٣٦٠° — أىّ الكسور يُعطى درجاتٍ صحيحة؟")
    good, bad = [], []
    for d in range(2, 65):
        if 360 % d == 0:
            good.append((d, 360 // d))
    print("   كسورٌ تُعطى عددًا صحيحًا من الدرجات:")
    print("   " + " · ".join(f"{d}={v}°" for d, v in good))
    print("\n   والزوایا التى يستعملها جان فعلًا (من خطاب الصويا والبنّ):")
    for a in (45, 60, 90, 120, 135, 180, 225, 240, 270, 300, 315, 360):
        print(f"   {a:>3}° = {a/360:.4f} من الدائرة = {360//math.gcd(360,a)} جزءًا"
              f"   (كسر {a//math.gcd(360,a)}/{360//math.gcd(360,a)})")
    print("   ⇒ كلها كسورٌ صحيحة للدائرة: 1/8 · 1/6 · 1/4 · 1/3 · 3/8 · 1/2 …")
    print("     وهذا سبب استعمالها: لا كسور عشرية، فتُحسب باليد وتُرسم على ورقٍ مسطّر.")


