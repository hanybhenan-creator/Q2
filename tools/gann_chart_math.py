def audit_squaring():
    hdr("٧. تربيع السعر بالزمن — أين يلتقى الإحداثيان")
    print("   من قاعٍ P₀ فى تاريخ t₀، بسرعة s (نقطة/يوم):")
    print("     السعر عند الزمن n يومًا:  P = P₀ + s·n")
    print("     الدرجة المقطوعة:          θ = (P − P₀)/s = n   ← **يتساويان بالبناء**")
    print("   ⇒ «نقطة = يوم» ليست قاعدة سوقية، بل نتيجةُ التعريف. والاختبار الحقيقى:")
    print("     هل يتحرك السعر فعلًا بمعدّل s ثابت للأداة نفسها؟")
    print()
    print("   وفى خطاب البنّ: القاع 435 (16/4/1931) والقمة 8729 (19/3/1954):")
    import datetime as dt
    d0, d1 = dt.date(1931, 4, 16), dt.date(1954, 3, 19)
    days = (d1 - d0).days
    months = 276
    print(f"     الأيام الحقيقية: {days}   ·   الأشهر: {months}")
    for name, rate, n in (("50 نقطة/شهر", 50, months), ("40 نقطة/شهر", 40, months),
                          ("30 نقطة/شهر", 30, months), ("1 نقطة/يوم", 1, days)):
        p = 435 + rate * n
        print(f"     {name:>12} × {n:>4} = {rate*n:>7}  ⇒  P = {p:>7}  "
              f"(الفارق عن 8729: {8729-p:>6} = {abs(8729-p)/8729*100:5.2f}%)")
    print("   ⇒ الذى يصحّ على **هذه** المسافة هو ٣٠ نقطة/شهر (فرق 0.16%) أو ١/يوم (0.91%).")
    print("     و50 و40 لا يصحّان هنا. ولو استُعملا لَلزم تاريخٌ آخر للقمة:")
    for rate in (50.0, 40.0, 30.0):
        need = (8729 - 435) / rate
        print(f"       بمعدل {rate:>4.0f} نقطة/شهر: يلزم {need:6.1f} شهرًا، "
              f"والواقعى 276  ⇒ فرق {need-276:+7.1f} شهرًا")
    print("   ⇒ المعدّل والمدة يُختاران معًا. فالمقياس الحرّ يعطى **دائمًا** مطابقةً")
    print("     بتاريخٍ ما — ولهذا لا تُثبت مطابقةٌ واحدة أن المقياس هو مقياس الأداة.")
    print("     والذى يُثبته: أن يعمل المقياس نفسه على كل القمم والقيعان، بلا اختيار.")


