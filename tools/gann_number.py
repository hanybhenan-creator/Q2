#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
وحدة القياس عند جان: تحويل أي رقم إلى درجة على الدائرة، ثم إرجاعه.

الفكرة الجوهرية — وهي التي تفرّق جان عن كل ماسح:
    جان لا يقارن السعر بالزمن. هو يعطي الاثنين **الوحدة نفسها**: الدرجة.
    فإذا صار السعر 38 درجة والزمن 38 درجة، فهما الشيء نفسه، لا شيئان متشابهان.
    وهذا معنى «تربيع السعر والزمن»: ليس تشابهًا، بل **تطابق وحدة**.

الصيغ المنشورة (Square of Nine):
    الدرجة = ( √N × 180 − 225 ) mod 360
    الرقم  = ( (الدرجة + 225) / 180 )²
    دورة كاملة (±360°) = ( √N ± 2 )²

ولأن التحويل جذري لا خطي، تظهر نتيجة لا توجد في أي مؤشر:
    **الدورة السعرية الواحدة ليست مقدارًا ثابتًا ولا نسبة ثابتة.**
    عند 100: دورة كاملة = 144 − 100 = 44
    عند 400: دورة كاملة = 484 − 400 = 84
    فهي تنمو مع الجذر، لا مع السعر.

التشغيل:
    python3 tools/gann_number.py                 # عرض توضيحي
    python3 tools/gann_number.py 38 --price      # 38 → درجة
    python3 tools/gann_number.py 132.25 --time   # رقم → درجة
    python3 tools/gann_number.py 100 10 --speed  # سرعة السعر: 10 وحدات سعر في 10 وحدات زمن
"""

import math
import sys


def total_degrees(n: float) -> float:
    """الدرجات التراكمية على اللولب — بلا لفّ.

    هذا هو المقياس الصحيح للحركة: الدالة الرقمية (mod) تعطي **الموضع** على
    الدائرة، وهذه تعطي **المسافة المقطوعة**. والفرق بينهما جوهري: رقم يمكن
    أن يعود إلى الموضع نفسه بعد دورة كاملة، وهو أبعد لا أقرب.
    """
    if n <= 0:
        raise ValueError("الرقم يجب أن يكون موجبًا")
    return math.sqrt(n) * 180.0 - 225.0


def to_degrees(n: float) -> float:
    """الموضع على دائرة 360 — للتمركز فقط، لا للمسافة."""
    return total_degrees(n) % 360.0


#  ─────────────────────────────────────────────────────────────────────
#  الكسور: لا وجود لها على المربع
#
#  المربع التسعة شبكة خلايا صحيحة: 144 خلية، ثم 145 خلية. لا 144.5.
#  والكسر ليس رقمًا على الشبكة، بل **موضع بين خليتين**. فطريقة حسابه:
#      درجة(144.5) = درجة(144) + 0.5 × عرض الخلية من 144 إلى 145
#  ولا تُحسب بجذر 144.5 — لأن الجذر يفترض استمرارًا لا وجود له على الشبكة.
#
#  وهذا نصّ ميكولا (الجزء 2، ف4، عن الخريطة الدائرية):
#      «290 تقع على 0° 00' و291 على 15° 00'، فنصف المسافة بينهما
#       نصف المسافة بين هذين الطولين، أي أن 290‑1/2 = 7° 30'.»
#  أي **استيفاء بين خليتين**، لا جذر عدد عشري.
#  ─────────────────────────────────────────────────────────────────────


def cell_angle(n: int) -> float:
    """درجة **خلية** صحيحة. ترفض الكسور: المربع لا يحملها."""
    if float(n) != int(n):
        raise ValueError(
            f"{n} ليس خلية صحيحة. المربع التسعة لا يحمل كسورًا — "
            f"استعمل angle_of() للاستيفاء بين خليتين."
        )
    if n <= 0:
        raise ValueError("الخلية يجب أن تكون موجبة")
    return to_degrees(float(n))


def cell_step(n: int) -> float:
    """العرض الزاوي للخلية n — أي المسافة من n إلى n+1.

    وليست ثابتة: الأكبر عند زوايا المربع (المربعات الكاملة)، والأصغر
    في وسط الأضلاع. فالثُمن ليس مقدارًا واحدًا في كل المربع.
    """
    return (cell_angle(n + 1) - cell_angle(n)) % 360.0


def angle_of(x: float) -> float:
    """درجة رقم قد يحمل كسرًا — باستيفاء **بين الخليتين** لا بجذر الكسر."""
    base = int(math.floor(x))
    frac = x - base
    if base < 1:
        raise ValueError("الرقم يجب أن يكون ≥ 1")
    return (cell_angle(base) + frac * cell_step(base)) % 360.0


def subdivisions(n: int, denom: int = 8) -> list:
    """تقسيم الخلية n إلى أجزاء متساوية — الثُمن ونصفه والربع…

    هذا هو «الربع والنصف والأرباع الثلاثة» بين 144 و145.
    """
    if n < 1:
        raise ValueError("الخلية يجب أن تكون ≥ 1")
    a0, step = cell_angle(n), cell_step(n)
    return [(k, a0 + step * k / denom) for k in range(denom + 1)]


def to_number(deg: float) -> float:
    """درجة ← رقم."""
    return ((deg + 225.0) / 180.0) ** 2


def rotate(n: float, turns: float) -> float:
    """تدوير الرقم حول الدائرة. turns=1 دورة كاملة، 0.25 ربع، -0.5 نصف للخلف.

    تنبيه على الالتباس الأشهر: «نصف» هنا تعني **نصف دورة** (180°)،
    وهي ليست «نصف خلية» (144.5). الاثنان يُسمَّيان نصفًا، وحجماهما مختلفان.
    """
    return (math.sqrt(n) + 2.0 * turns) ** 2


def cycle_length(n: float) -> float:
    """طول الدورة السعرية الواحدة من المستوى n — أي مقدار السعر الذي يقطعه في 360°."""
    return rotate(n, 1.0) - n


def separation_deg(a: float, b: float) -> float:
    """المسافة الزاوية بين رقمين على الدائرة، 0..180. تقبل الكسور بالاستيفاء."""
    d = abs(angle_of(a) - angle_of(b)) % 360.0
    return min(d, 360.0 - d)


def speed(price_from: float, price_to: float, time_from: float = 0.0,
          time_to: float = 0.0) -> dict:
    """سرعة السعر: درجة سعرية لكل درجة زمنية — أي معدل الاهتزاز.

    تُقاس على الدرجات التراكمية لا الملفوفة، وإلا عاد الرقم إلى الصفر
    بعد دورة كاملة فبدت الحركة الكبيرة سكونًا.

    وبما أن المعامل 180 يلغي نفسه، فالسرعة = (√س₂ − √س₁) ÷ (√ز₂ − √ز₁).
    وسرعة = 1 تعني **1×1**: تساوي درجات السعر ودرجات الزمن.
    """
    # الزمن يُقاس من الصفر (لحظة القمة/القاع)، والسعر من مستواه،
    # فالمقارنة على الفروق لا على القيم المطلقة.
    dp = math.sqrt(price_to) - math.sqrt(price_from)
    dt = math.sqrt(max(time_to, 0.0)) - math.sqrt(max(time_from, 0.0))
    if abs(dt) < 1e-9:
        raise ValueError("الزمن لم يتحرك")
    ratio = dp / dt
    return {
        "price_deg": dp * 180.0,
        "time_deg": dt * 180.0,
        "speed": ratio,
        "label": _speed_label(ratio),
    }


def _speed_label(ratio: float) -> str:
    r = abs(ratio)
    if r > 2.2:
        return "أسرع من 2×1 — حركة حادة"
    if r > 1.15:
        return "بين 1×1 و2×1"
    if r >= 0.87:
        return "1×1 — الوحدة بالوحدة"
    if r >= 0.45:
        return "بين 1×2 و1×1"
    return "أبطأ من 1×2 — حركة هادئة"


def demo() -> None:
    print("=" * 72)
    print("  ١) الرقم نفسه، والمعنى يختلف بالكلمة")
    print("=" * 72)
    print("  38 كسعرٍ و38 كيوم: الدرجة واحدة، والموقع واحد على الدائرة.")
    print(f"     درجة 38 = {to_degrees(38):.2f}°")
    print("     لكن 38 قرشًا و38 يومًا ليسا الشيء نفسه في العالم.")
    print("     الوحدة هي ما يعطي الرقم معناه — لا الرقم وحده.")
    print()

    print("=" * 72)
    print("  ٢) الدورة السعرية ليست ثابتة — وهذا ما لا يقوله أي مؤشر")
    print("=" * 72)
    print(f"  {'السعر':>10} {'+دورة 360°':>14} {'مقدار الحركة':>14} {'كنسبة':>10}")
    for p in (25, 50, 100, 200, 400, 800):
        c = cycle_length(p)
        print(f"  {p:>10} {rotate(p, 1.0):>14.2f} {c:>14.2f} {c/p*100:>9.1f}%")
    print()
    print("  المقدار ينمو مع الجذر لا مع السعر: من 25 إلى 800 (32 ضعفًا)")
    print("  تكبر الدورة 4.9 ضعفًا فقط. فهي ليست مبلغًا ولا نسبة.")
    print()

    print("=" * 72)
    print("  ٣) سرعة السعر — معدل الاهتزاز في صيغة قابلة للقياس")
    print("=" * 72)
    cases = [(100, 110, 0, 10), (100, 144, 0, 10), (100, 130, 0, 30),
             (100, 156.25, 0, 20)]
    for p0, p1, t0, t1 in cases:
        s = speed(p0, p1, t0, t1)
        print(f"  {p0}→{p1:>7.2f} في {t1-t0:>2} يومًا:  "
              f"{s['price_deg']:+8.2f}° سعر / {s['time_deg']:+8.2f}° زمن "
              f"= {s['speed']:+5.2f}  ({s['label']})")
    print()

    print("=" * 72)
    print("  ٤) الكسور: ليست على المربع، بل بين 144 و145")
    print("=" * 72)
    print(f"  عرض الخلية 144 → 145 = {cell_step(144):.4f}°")
    print(f"  {'الموضع':<10}{'الدرجة':>10}   {'مقدار الزيادة':>14}")
    for label, val in (("144", 144.0), ("144 ربع", 144.25), ("144 نصف", 144.5),
                       ("144 ثلاثة أرباع", 144.75), ("145", 145.0)):
        print(f"  {label:<12}{angle_of(val):>9.4f}°   {angle_of(val) - cell_angle(144):>+13.4f}°")
    print()
    try:
        cell_angle(144.5)
    except ValueError as exc:
        print(f"  وخلية بكسر تُرفض: {exc}")
    print()
    print("  وبالجذر (الطريقة الخاطئة) يعطي 144.5 ←",
          f"{(math.sqrt(144.5) * 180 - 225) % 360:.4f}°")
    print("  الفرق صغير هنا لأن الخلية قصيرة — لكنه يصير خطأً فادحًا")
    print("  حين يُخلط «نصف خلية» بـ«نصف دورة».")
    print()

    print("=" * 72)
    print("  ٥) ثلاثة «أنصاف» مختلفة — والخلط بينها هو الخطأ")
    print("=" * 72)
    print(f"  نصف خلية   (144 → 144.5)      = {cell_step(144)/2:>8.3f}°")
    print(f"  نصف دورة   (√144 + 1)         = {180.0:>8.3f}°   → السعر {rotate(144, 0.5):.2f}")
    print(f"  نصف درجة   (السعر 97.5 = 30') = {0.5:>8.3f}°   (كسر الدرجة نفسها)")
    print()
    print("  الثلاثة كلها تُسمَّى «نصفًا». وأحجامها: 3.74° و180° و0.5°.")
    print("  وعلى المربع: الكسر دائمًا **بين خليتين**، لا داخل الرقم.")
    print()

    print("=" * 72)
    print("  ٦) تربيع السعر والزمن — التطابق لا التشابه")
    print("=" * 72)
    print("  السعر 144 = 12² ، الزمن 324 يومًا = 18².")
    print(f"     موضع السعر = {to_degrees(144):.2f}°")
    print(f"     موضع الزمن = {to_degrees(324):.2f}°")
    print(f"     الفصل      = {separation_deg(144, 324):.2f}°")
    print("  المستوى 144 والزمن 324 يقعان على الموضع نفسه من الدائرة.")
    print("  هذه هي «التربيع»: تطابق وحدة، لا تشابه سلوك.")
    print()
    print("  واختبر بعينك: 12² = 144 سعرًا، 18² = 324 يومًا —")
    print("  كلاهما مربع كامل، فوقعا على المحور نفسه. هذا معنى «رقم بمربع».")


def main() -> None:
    args = sys.argv[1:]
    if not args:
        demo()
        return
    if "--speed" in args:
        i = args.index("--speed")
        p0, t0 = float(args[0]), float(args[1])
        p1, t1 = float(args[i + 1]), float(args[i + 2])
        s = speed(p0, p1, t0, t1)
        print(f"درجة السعر: {s['price_deg']:+.3f}°")
        print(f"درجة الزمن: {s['time_deg']:+.3f}°")
        print(f"السرعة: {s['speed']:+.4f}  — {s['label']}")
        return
    if not args or args[0] in ("-h", "--help"):
        print(__doc__.strip().split("\n\n")[-1])
        return
    n = float(args[0])
    total = total_degrees(n)
    print(f"الموضع على الدائرة : {total % 360.0:.4f}°")
    print(f"إجمالي الدرجات     : {total:.4f}°  (دورات كاملة: {total // 360.0:.0f})")
    print(f"رجوعًا من الإجمالي : {to_number(total):.4f}  ← يعيد {n:g} بالضبط")
    print(f"دورة كاملة +       : {rotate(n, 1.0):.4f}   (مقدارها {cycle_length(n):.4f})")


if __name__ == "__main__":
    main()
