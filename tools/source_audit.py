def audit_coffee():
    rule("٣. خطاب البنّ (19/3/1954) — السعر 8729 بأربعة مقاييس")
    print("""  نصّ جان (المطبوع فى الماستر كورس، ch.20):
     «Using a scale of one point to one degree, 8729 equals 29° Gemini.»
     «Using a scale of 30 points to one degree, equals 21° Capricorn.»
     «Using the Jupiter scale of 12 points to one degree, equals 7°30′ Aries.»
     «Using **one cent** to one degree, equals 27°16′ Gemini.»
""")
    rows = [("1 point = 1°", 8729 / 1, 89.0, "29° Gemini"),
            ("30 points = 1°", 8729 / 30, 290.9667, "21° Capricorn"),
            ("12 points = 1° (Jupiter)", 8729 / 12, 7.5, "7°30′ Aries"),
            ("1 cent = 1°  (8729 pts = 87.29¢)", 8729 / 100, 87 + 16 / 60, "27°16′ Gemini")]
    print(f"  {'المقياس':34s} {'8729 ÷ s':>10s} {'الدرجة':>18s} {'نصّه':16s} فرق")
    for name, q, claimed, text in rows:
        d = ((q - claimed + 180.0) % 360.0) - 180.0
        d = abs(d)
        print(f"  {name:34s} {q:10.2f} {deg(q):>18s} {text:16s} {d:.2f}°")
    print("""
  ⇒ أربعةُ مقاييس منصوصة، والأربعة تُنتج ما كتبه. لكن الرابع ليس «1 دولار = 1°»
     كما فى `04 §23.4` و`06 §1`: فالدولار = 100 سنت = 10,000 حنّة، و«1 دولار = 1°»
     يعطى 0.87° لا 87.29°. **الصواب: 1 سنت = 1°** — أى القسمة على 100.

  وفى الصفحة نفسها مقاييس أخرى غير السعر→الدرجة:
     50 نقطة/شهر · 40 نقطة/شهر · 30 نقطة/شهر · 45 نقطة/درجة · 30 نقطة/درجة.
  ⇒ المقياس فى الخطابين **يُختار لكل مسألة**، ولا يُعلَن مرّةً واحدة.""")

    print("""
  والوحدة تُثبَّت بلا سعرٍ خارجى — من سطرٍ واحد فى الخطاب:
     «The dollar value is $28,171.00»  و«average price of 5 options = 8663»
     28,171 ÷ 0.8663 دولار/رطل = 32,519 رطل
     وعقد «Santos D» فى بورصة نيويورك = **32,500 رطل** (0.06% فرق)
  ⇒ 8663 حنّة = 86.63 سنتًا · و1 حنّة = 0.01 سنت. فقاعدة «العلامة لا وجود لها» صحيحة:
    الرقم مكتوبٌ بلا فاصلة، وموضع القراءة هو المتغيّر.""")


