def audit_document():
    rule("١. الوثيقة — ما نوعها، وبأى دقة؟")
    try:
        import pymupdf
    except ImportError:
        print("  pymupdf غير مثبّت ⇒ تخطَّ.  pip install --user pymupdf")
        return
    print(f"  {'الملف':34s} {'ص':>3s} {'نصّ الصفحة':>11s} {'صورة داخلية':>13s}  الحكم")
    for name, pages in PDFS:
        path = os.path.join(ROOT, name)
        if not os.path.exists(path):
            print(f"  {name:34s}  —  (مفقود)")
            continue
        doc = pymupdf.open(path)
        for i, page in enumerate(doc):
            txt = len(page.get_text().strip())
            imgs = page.get_images(full=True)
            px = ""
            if imgs:
                im = doc.extract_image(imgs[0][0])
                px = f"{im['width']}×{im['height']}"
                verdict = "مسحٌ ضوئى منخفض الدقة" if im["width"] < 1000 else "مسحٌ عالى"
            else:
                verdict = "طبقة نصّ مولَّدة"
            print(f"  {name:34s} {i+1:>3d} {txt:>11d} {px:>13s}  {verdict}")
        doc.close()
    print("""
  ⇒ ثلاث نتائج:
     ١. لا طبقة نصّ فى صفحات المحتوى (0–189 حرفًا: الغلاف فقط) ⇒ كل قراءة بشرية.
     ٢. الصورة المدمجة 601×632 بكسل للصفحة الواحدة ⇒ لا تُقرأ الأرقام الصغيرة بثقة،
        والالتباس فى الأرقام (23ĵ° · 111.52 · 181°35′) متوقَّع من المسح لا من جان.
     ٣. الغلاف يقول «published by Gann Study Group · not to be sold» ⇒
        **ليست من الموقع الرسمى** (wdgann.com / Lambert-Gann). فهى نسخةٍ ثالثة.
     والخطاب نفسه منشورٌ رسميًّا فى: W.D. Gann Master Commodities Course (1954)، ch.20.""")


