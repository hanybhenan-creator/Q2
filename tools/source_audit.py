def audit_soy():
    rule("٢. خطاب الصويا (18/1/1954) — أى مقياس يُنتج ما كُتب؟")
    print("  العمود «1:1» = 1 حنّة (سنت) = 1°  ·  العمود «15°» = 24 سنتًا = 360°\n")
    print(f"  {'السعر':>9s} {'نصّ جان':22s} {'1:1':>16s} {'15°/سنت':>16s}  من يطابق")
    ok11 = ok15 = 0
    for price, claimed, text in SOY_RESISTANCE:
        a, b = price % 360, (price * 15) % 360
        m11 = abs(a - claimed) < 0.6
        m15 = abs(b - claimed) < 0.6 or abs(abs(b - claimed) - 360) < 0.6
        ok11 += m11
        ok15 += m15
        who = ("1:1" if m11 else "") + ("+15°" if m15 else "")
        print(f"  {price:9.3f} {text:22s} {deg(a):>16s} {deg(b):>16s}  {who or '✘ لا شىء'}")
    print(f"\n  ⇒ «PRICE RESISTANCE LEVELS»: 1:1 يطابق {ok11}/{len(SOY_RESISTANCE)} · "
          f"و15°/سنت يطابق {ok15}/{len(SOY_RESISTANCE)}")

    print("\n  وجدول الصفحة ٤ (نفس الخطاب):")
    for price, claimed, text in SOY_24C:
        b = (price * 15) % 360
        m = abs(b - claimed) < 0.6 or abs(abs(b - claimed) - 360) < 0.6
        one = abs(price % 360 - claimed) < 0.6
        who = "✔ 15°/سنت" if m else ("✔ 1:1" if one else "✘")
        print(f"  {price:9.3f} {text:22s} {deg(b):>16s}  {who}")
    print("""  ⇒ الملف نفسه يحمل **مقياسَين متعارضين**:
       ص٢–٣: السعر = الدرجة (1:1) — 12 سطرًا، 12/12، ولا سطر منها يصحّ بـ15°.
       ص٤  : 24 سنتًا = 360° (15° للسنت) — أربعة أسطر كلها بـ15°، والخامس (زحل) بـ1:1.
     والتعارض صريح على **الرقم الواحد**:
       ٣٠٠ ← «30° Capricorn» (ص٣، 1:1)   و  ٣٠٠ ← «30° Virgo» (ص٤، 24 سنتًا)
       ٣٠٣ ← سعر زحل 8°30′ العقرب (1:1)   و  ٣٠٤ ← «30° Scorpio» (15°/سنت)
     ⇒ فلا «مفتاحٌ واحد للخطاب»؛ بل مقياسان يعملان معًا، ولا قاعدة تختار بينهما.""")

    print("""
  وتنبيه على أداة المستودع: `letter_keys.py` يجرّب الصويا على 5 أسطر فقط،
  كلها من ص٣–٤، ويقبل 15°/سنت 5/5. وأحد أسطرها («308½ square to Saturn»)
  كُتب هدفُه 307.5 = 308.5×15 — وهو **دورٌ فى الحساب**: درجةُ السطر فى نصّ جان
  هى 308.5 نفسها (= زحل 218.5 + 90)، أى 1:1. فاحتُسب السطر لصالح 15° خطأً.
  ⇒ 5/5 ليست نتيجةَ استنفاد، بل نتيجة **اختيار** — والمستودع نفسه يمنع الاقتطاع.""")


