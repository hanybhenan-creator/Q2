#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
القياسات المستورة — نحوٌ من كتاب ١٦٦٧ «Times of the Bible».

الكتاب (لندن ١٦٦٧) يبنى على قاعدةٍ واحدة: **الرقم الواحد يصلح لكل وحدة**،
و**الكلمة التالية** هى التى تُعيّنه. فالعدد ١٢٠ فى الكتاب يظهر:
   ١٢٠ سنة (بناء الفلك) · ١٢٠ ساعة (قبل يوم آدم) · ١٢٠ ذراعًا (حجاب الخيمة)
   · ١٢٠ شاقلًا (ذهبًا) · ١٢٠ يومًا (مجىء عزرا) · ١٢٠ كاهنًا (الأبواق).
والعدد ٤٨٠: ٤٨٠ سنة (من الخروج إلى الهيكل) · ٤٨٠ ذراعًا · ٤٨٠ ساعة · ٤٨٠ لوحًا.
والعدد ١٢٦٠: ١٢٦٠ سنة · ١٢٦٠ يومًا · ١٢٦٠ ساعة.
والعدد ١٦٠٠ غلوة (رؤ ١٤:٢٠) ← ١٦٠٠ سنة ← ١٦٦٦ · ١٦٧٥.

فهذا الملف يُجرّد **نحوَ التحويل** من الكتاب ويُطبّقه:
  ١. جدول الوحدات الثمانى وعلاقتها بالزمن.
  ٢. تحويل أعداد الكتاب إلى كل وحدة، ومقارنتها بالأحداث التى يذكرها هو.
  ٣. تطبيق النحو نفسه على أرقام خطاب جان (8729 / 87.29 / 435 / 8663 / 28,171).
  ٤. تطبيقه على سعر مصرى — وإظهار أن **اختيار الوحدة يُغيّر النتيجة**،
     وأن الوحدة لا تُختار بالنظر بل تُعلن قبل الحساب.

التشغيل:
    python3 tools/veiled_measures.py
"""

from fractions import Fraction

LINE = "=" * 82


def hdr(t):
    print("\n" + LINE + "\n " + t + "\n" + LINE)


# ─────────────────────────────────────────────────────────────────────
# ١. النحو — الوحدات الثمانى
# ─────────────────────────────────────────────────────────────────────

# الوحدة ← (ما تعدّه، معاملها باليوم)
UNITS = [
    ("ساعة",        "١/٢٤ يوم",   Fraction(1, 24)),
    ("يوم",         "١ يوم",       Fraction(1)),
    ("أسبوع",       "٧ أيام",      Fraction(7)),
    ("شهر (٣٠)",    "٣٠ يومًا",    Fraction(30)),
    ("سنة نبوية",   "٣٦٠ يومًا",   Fraction(360)),
    ("سنة شمسية",   "٣٦٥.٢٤٢٢",    Fraction(3652422, 10000)),
    ("أسبوع سنين",  "٧×٣٦٠ = ٢٥٢٠", Fraction(2520)),
    ("يوبيل",       "٤٩ سنة",      Fraction(49 * 360)),
]

# الوحدات المِترية/النقدية فى الكتاب — وكلها «تُقرأ» زمنًا
MEASURES = [
    ("ذراع",   "طول — وفى الكتاب: يومًا/سنةً"),
    ("شيكل",   "وزن ذهب/فضة — وفى الكتاب: وقتًا"),
    ("وزنة",   "٣٠٠٠ شيكل"),
    ("غلوة",   "مسافة — وفى الكتاب: سنةً (١٦٠٠ غلوة ← ١٦٠٠ سنة)"),
    ("كور",    "مكيال"),
    ("بثّ",    "مكيال"),
]


def grammar():
    hdr("١. نحو التحويل — ما يقوله الكتاب")
    print("  القاعدة:  «العدد + الوحدة = مقدارٌ من الزمن»")
    print("  ولا وجود لرقمٍ بلا وحدته؛ فالرقم نفسه يكون سنةً أو يومًا أو ساعةً أو ذراعًا.\n")
    print(f"  {'الوحدة':12} {'قيمتها':16} {'بالأيام':>12}")
    for name, desc, days in UNITS:
        print(f"  {name:12} {desc:16} {float(days):>12,.4f}")
    print()
    for name, desc in MEASURES:
        print(f"  {name:8} — {desc}")
    print("\n  ⇒ النحو ستّة أزواج: (عدد، وحدة) ← زمن. وكلُّ تحويلٍ فى الكتاب من هذا الشكل.")


# ─────────────────────────────────────────────────────────────────────
# ٢. أعداد الكتاب — كلُّ وحدةٍ تُعطى تاريخًا مختلفًا
# ─────────────────────────────────────────────────────────────────────

BOOK_NUMBERS = {
    120: "الفلك · حجاب الخيمة · ذهب المواهب · أبواق · أيام عزرا · ساعة آدم",
    144: "ألواح المائدة · ساعات الأسبوع (٦ أيام)",
    480: "من الخروج إلى الهيكل · ذراعًا · ساعة · لوحًا",
    1260: "سنوات الردّة · أيام · ساعات",
    1290: "من إزالة الذبيحة (دانيال ١٢:١١)",
    1335: "طوبى للمنتظر (دانيال ١٢:١٢)",
    1500: "ذراعًا · شاقلًا · ساعة",
    1600: "غلوة (رؤ ١٤:٢٠) · سنة",
    2300: "مساء وصباح (دانيال ٨:١٤)",
    3000: "سنوات العالم · ذراعًا · شاقلًا · مَثَلًا",
    4000: "سنوات العالم · ذراعًا",
    7000: "ذراعًا مظلَّلًا · ألف سنة",
}


def book_numbers():
    hdr("٢. أعداد الكتاب — بأى وحدةٍ وفى أى موضع؟")
    print(f"  {'الرقم':>6}  {'أين ذكره الكتاب':46}  {'بالسنين':>9} {'بالأيام':>10}")
    for n, where in sorted(BOOK_NUMBERS.items()):
        print(f"  {n:>6}  {where:46}  {n:>9,} {n*360:>10,}")
    print("""
  ⇒ لاحظ: ١٦٠٠ غلوة ← ١٦٠٠ سنة ← «تنتهى بين ١٦٦٦ و١٦٧٥» كما قال الكتاب.
     فالغلوة **ليست مسافة** فى حساب المؤلّف، بل **وحدة زمن** — والكلمة هى التى
     حوّلتها. وهذا هو عينُ ما نفعله بسعر السهم حين نقرأ ٣٨ قرشًا أو ٣٨ يومًا.""")


# ─────────────────────────────────────────────────────────────────────
# ٢ب. تحويلات الكتاب نفسه — مستخرَجة من نصّه لا من خارجه
# ─────────────────────────────────────────────────────────────────────

def book_conversions():
    hdr("٢ب. تحويلات يُصرّح بها الكتاب — وناتجها بالحساب")
    print("  ص٨: «١٦٠٠ غلوة … سنوات» · «٧٠٠٠ ذراعًا مظلَّلًا … كألف سنة»")
    print("  ص٤٤: «قد تكون ساعاتٍ كما هى سنواتٍ وأيامًا»\n")
    rows = [
        ("غلوة", 1600, "سنة", 1600, "١ غلوة = ١ سنة"),
        ("ذراع", 7000, "سنة", 1000, "٧ أذرع = ١ سنة"),
        ("ساعة", 144, "من الأسبوع", 168, "١٤٤ = ٦/٧ الأسبوع"),
        ("شهر", 3600, "ساعة", 5, "٣٦٠٠ ساعة = ١٥٠ يومًا"),
    ]
    print(f"  {'الوحدة':7} {'العدد':>7} {'تقابل':>14} {'العدد':>7} {'النتيجة':>26}")
    for u, n, u2, n2, note in rows:
        print(f"  {u:7} {n:>7} {u2:>14} {n2:>7} {note:>26}")

    yr = 365.2422
    print(f"""
  ⇒ والذراع بالحساب: ‎{1000*yr/7000:.3f}‎ يومًا = ‎{1000*yr/7000/7:.3f}‎ أسبوعًا.
     فالسنة على مقياس الكتاب = ٧ أذرع بالضبط. وهذا **السبع** نفسه الذى أخرج
     ٢٥٢٠ من عائلة ٢·٣·٥ عند Heath (tools/harmonics.py §١) — فالدائرتان
     تُفترقان عند السبعة، لا عند غيرها.""")


# ─────────────────────────────────────────────────────────────────────
# ٣. النحو على خطاب جان
# ─────────────────────────────────────────────────────────────────────

def gann_letters():
    hdr("٣. النحو نفسه على أرقام جان — الوحدة تُعلَن فى النصّ")
    print("  خطاب القهوة ١٩/٣/١٩٥٤ — السعر 8729، ونصُّه:")
    print('   «one point to one degree» · «30 points to one degree» ·')
    print('   «12 points to one degree» · «one cent to one degree»\n')

    readings = [
        ("8729 نقطة", 8729 / 1, "1°", 8729 % 360),
        ("8729 = 87.29 سنتًا", 8729 / 100, "1°", 87.29 % 360),
        ("8729 = 872.9", 8729 / 10, "1°", 872.9 % 360),
        ("8729 = 8.729", 8729 / 1000, "1°", 8.729 % 360),
        ("8729 ÷ 12", 8729 / 12, "1°", (8729 / 12) % 360),
        ("8729 ÷ 30", 8729 / 30, "1°", (8729 / 30) % 360),
    ]
    print(f"  {'القراءة':24} {'الدرجة':>10}")
    for label, v, _, deg in readings:
        print(f"  {label:24} {deg:>10.2f}°   نصّ جان: {'29° Gemini' if abs(deg-89)<1e-6 else ''}")
    print("""
  ⇒ سطران من الأربعة يُعطيان 29° الجوزاء و27°16′ الجوزاء، وهما قراءتان **لرقم واحد**
     بموضعين للفاصلة. فالمسألة ليست حسابًا، بل **تعيينُ الوحدة** — وهذا نصُّ
     الكتاب ١٦٦٧ بحرفه: العددُ يُعرف بالكلمة التالية.

  والوحدة تُثبَّت من داخل الخطاب لا من خارجه:
     «The dollar value is $28,171» و«average price of 5 options = 8663»""")
    lb = 28171 / 0.8663
    print(f"     28,171 ÷ 0.8663 = {lb:,.0f} رطلًا   (عقد Santos D = 32,500)  ⇒ 1 حنّة = 0.01 سنت")


# ─────────────────────────────────────────────────────────────────────
# ٤. على سعر مصرى — الوحدة تُغيّر النتيجة
# ─────────────────────────────────────────────────────────────────────

EGX = [
    ("قرش",    Fraction(1, 100), "1 جنيه = 100 قرش (نصّ البورصة)"),
    ("جنيه",   Fraction(1),      "الوحدة الأصلية"),
    ("نقطة",   Fraction(1, 100), "نظير «point» عند جان"),
    ("دولار",  Fraction(100, 73), "بسعر صرفٍ ٧٣ — ويتغيّر كل يوم"),
]


def egx_units(price=38.0):
    hdr("٤. سعر واحد (٣٨) بأربع وحدات — أربع درجات")
    print(f"  السعر المُعطى: {price}  (بلا وحدة — كما كتب جان)\n")
    print(f"  {'الوحدة':8} {'المقدار بالقرش':>14} {'الدرجة (mod 360)':>18}")
    for name, f, note in EGX:
        q = price / float(f)
        print(f"  {name:8} {q:>14,.2f} {q % 360:>18.2f}°   {note}")
    print("""
  ⇒ من الرقم ٣٨ وحده تخرج أربع درجات مختلفة تمامًا. والفرق ليس حسابًا خاطئًا،
     بل **تعيينًا للوحدة**. ومن لم يُعلن وحدته قبل النظر، اختار الدرجة التى تُوافق
     النتيجة التى يريدها — وهو الفرق بين قياسٍ واختيار.""")


def main():
    grammar()
    book_numbers()
    book_conversions()
    gann_letters()
    egx_units()
    print("\n" + LINE)
    print(" الخلاصة: الكتاب ١٦٦٧ يُعطى النحو، وجان يُعطى التطبيق، والوحدة تُعلَن أولًا.")
    print(LINE)


if __name__ == "__main__":
    main()
